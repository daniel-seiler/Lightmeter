"""Generates src/bitmap_generated.{hpp,cpp} from the PNGs in res/ and res/sprites.json.

An animation in sprites.json rotates its PNG around "pivot". The image has to repeat itself
after "period_deg" degrees (one gear tooth) for the frames to loop.
"""
import glob
import json
import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "res")
SRC = os.path.join(ROOT, "src")
SUPERSAMPLE = 8


def rotate(img, angle, pivot):
    return img.rotate(angle, resample=Image.BICUBIC, center=pivot)


def animation_frames(img, frames, pivot, period_deg):
    size = img.size
    big = img.resize((size[0] * SUPERSAMPLE, size[1] * SUPERSAMPLE), Image.NEAREST)
    valid = Image.new("L", big.size, 255)
    pivot = ((pivot[0] + 0.5) * SUPERSAMPLE, (pivot[1] + 0.5) * SUPERSAMPLE)
    result = [img]
    for i in range(1, frames):
        angle = period_deg * i / frames
        # Pixels the rotation pulls in from outside the image are taken from the rotation one
        # period behind
        frame = Image.composite(rotate(big, angle, pivot),
                                rotate(big, angle - period_deg, pivot),
                                rotate(valid, angle, pivot).point(lambda v: 255 if v > 250 else 0))
        frame = frame.resize(size, Image.BOX).point(lambda v: 255 if v >= 128 else 0)
        result.append(frame)
    return result


def to_pages(img):
    """Converts an image to the layout described at bitmap::Sprite."""
    width, height = img.size
    px = img.load()
    data = []
    for page in range((height + 7) // 8):
        for x in range(width):
            byte = 0
            for bit in range(8):
                y = page * 8 + bit
                if y < height and px[x, y]:
                    byte |= 1 << bit
            data.append(byte)
    return data


def main():
    with open(os.path.join(RES, "sprites.json")) as f:
        config = json.load(f)

    header = """// Generated by scripts/generate_header.py, do not edit.
#ifndef LIGHTMETER_BITMAP_GENERATED_HPP
#define LIGHTMETER_BITMAP_GENERATED_HPP

#include "bitmap.hpp"

namespace bitmap {
"""
    source = """// Generated by scripts/generate_header.py, do not edit.
#include "bitmap_generated.hpp"

namespace bitmap {
"""
    for name, (x, y) in config["positions"].items():
        header += f"    const uint8_t {name}_X = {x};\n"
        header += f"    const uint8_t {name}_Y = {y};\n"
    header += "\n"

    for img_path in sorted(glob.glob(os.path.join(RES, "*.png"))):
        name = os.path.basename(img_path)[:-4]
        img = Image.open(img_path).convert("L").point(lambda v: 255 if v >= 128 else 0)
        anim = config["animations"].get(name)
        frames = [img]
        if anim:
            frames = animation_frames(img, anim["frames"], anim["pivot"], anim["period_deg"])
        data = [b for frame in frames for b in to_pages(frame)]
        const = name.upper()
        header += f"    extern const Sprite {const};\n"
        if anim:
            header += f"    const uint8_t {const}_FRAMES = {len(frames)};\n"
        source += f"    static const uint8_t {const}_DATA[] PROGMEM = {{"
        for i, b in enumerate(data):
            if i % 16 == 0:
                source += "\n        "
            source += f"0x{b:02x}, "
        source += "\n    };\n"
        source += (f"    const Sprite {const} PROGMEM = "
                   f"{{{img.size[0]}, {img.size[1]}, {len(frames)}, {const}_DATA}};\n\n")

    header += "}\n\n#endif //LIGHTMETER_BITMAP_GENERATED_HPP\n"
    source += "}\n"
    with open(os.path.join(SRC, "bitmap_generated.hpp"), "w") as f:
        f.write(header)
    with open(os.path.join(SRC, "bitmap_generated.cpp"), "w") as f:
        f.write(source)


if __name__ == "__main__":
    main()
